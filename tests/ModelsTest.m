classdef ModelsTest < matlab.unittest.TestCase
    %MODELSTEST  Smoke tests: every parameter file runs and every Simulink model loads.
    %   Run with:  buildtool test

    properties (TestParameter)
        paramFile = struct( ...
            "quarterCar",   "01_quarter_car/Quarter_car_model_parameters.m", ...
            "dof4",         "02_dof4/DOF4_model_parameters.m", ...
            "dof7",         "03_dof7_shaker/Suspension_shaker_rig_model_parameters.m", ...
            "dof10",        "04_dof10_shaker/Suspension_shaker_rig_dof10_model_parameters.m", ...
            "dof14",        "05_dof14_full_vehicle/Complete_vehicle_simulation_dof14_model_parameters.m", ...
            "bicycle",      "06_bicycle/Bicycle_model_parameters_formula.m", ...
            "driving",      "07_longitudinal/Driving_dynamics_parameters.m", ...
            "longDriving",  "07_longitudinal/Longitudinal_driving_parameters.m", ...
            "braking",      "07_longitudinal/Longitudinal_braking_parameters.m", ...
            "pacejka",      "08_pacejka_tyres/Pacejka_lateral_parameters.m");

        model = struct( ...
            "quarterCar",   "01_quarter_car/Quarter_car_model.slx", ...
            "dof4",         "02_dof4/DOF4_model.slx", ...
            "dof7",         "03_dof7_shaker/Suspension_shaker_rig_model.slx", ...
            "dof10",        "04_dof10_shaker/DOF10_Suspension_shaker_rig_model.slx", ...
            "dof14",        "05_dof14_full_vehicle/Complete_vehicle_simulation_dof14_model.slx", ...
            "bicycle",      "06_bicycle/Bicycle_model.slx", ...
            "braking",      "07_longitudinal/Braking_dynamics_model.slx", ...
            "driving",      "07_longitudinal/Driving_dynamics_model.slx", ...
            "pacejkaLat",   "08_pacejka_tyres/Pacejka_lateral_tyre_model.slx", ...
            "pacejkaLong",  "08_pacejka_tyres/Pacejka_longitudinal_tyre_model.slx", ...
            "pacejka",      "08_pacejka_tyres/Pacejka_tyre_model.slx");
    end

    properties
        Root
    end

    methods (TestClassSetup)
        function setRoot(tc)
            tc.Root = fileparts(fileparts(mfilename("fullpath")));
        end
    end

    methods (Test)
        function parameterFileRuns(tc, paramFile)
            f = fullfile(tc.Root, paramFile);
            tc.verifyWarningFree(@() evalinIsolated(f));
        end

        function modelLoads(tc, model)
            f = fullfile(tc.Root, model);
            [~, name] = fileparts(f);
            load_system(f);
            tc.addTeardown(@() close_system(name, 0));
            tc.verifyTrue(bdIsLoaded(name));
        end
    end
end

function evalinIsolated(file)
% Run a parameter script in its own workspace so tests stay independent
run(file);
end
